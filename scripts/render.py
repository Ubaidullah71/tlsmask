"""Everything tlsmask generates from a tls-client release: _pins.py, profiles.py,
_version.py, the README's badge/stats/profile blocks, changelog entries and the
update bot's report.

    python scripts/render.py refresh                   # re-render from the current pins
    python scripts/render.py changelog-section 1.16.0  # one release's notes

Pure functions. tests/test_render.py checks the committed files are exactly
what they render, so a generated file is never edited by hand by accident.
"""

from __future__ import annotations

import argparse
import re
from collections.abc import Iterable, Mapping, Sequence
from pathlib import Path

import upstream

MONTHS = ("Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec")

# The old `tls-client` package (1.0.1, its last release, February 2024).
OLD_WRAPPER = {
    "library": "v1.7.2",
    "profiles": "51",
    "chrome": "120",
    "firefox": "120",
    "ios": "16.0",
    "updated": "Feb 2024",
}

CHROME = r"chrome_(\d+)(?:_PSK)?(?:_PQ)?"
FIREFOX = r"firefox_(\d+)(?:_PSK)?"
SAFARI_IOS = r"safari_ios_(\d+)_(\d+)"
BRAVE = r"brave_(\d+)(?:_PSK)?"

FAMILIES = (
    ("Chrome", ("chrome_",)),
    ("Firefox", ("firefox_",)),
    ("Safari (iOS & iPadOS)", ("safari_ios_", "safari_ipad_")),
    ("Safari (macOS)", ("safari_",)),
    ("Opera", ("opera_",)),
    ("Brave", ("brave_",)),
)
OTHERS = "Mobile apps & others"


def natural(name: str) -> list:
    return [int(part) if part.isdigit() else part for part in re.split(r"(\d+)", name)]


def family(name: str) -> str:
    for label, prefixes in FAMILIES:
        if name.startswith(prefixes):
            return label
    return OTHERS


def newest(profiles: Iterable[str], pattern: str) -> str:
    found = []
    for name in profiles:
        match = re.fullmatch(pattern, name)
        if match:
            found.append(tuple(int(group) for group in match.groups()))
    return ".".join(str(n) for n in max(found)) if found else "none"


def month_year(iso_date: str) -> str:
    year, month, _day = iso_date.split("-")
    return f"{MONTHS[int(month) - 1]} {year}"


def _codes(names: Iterable[str]) -> str:
    return ", ".join(f"`{name}`" for name in names)


# --- generated modules ---------------------------------------------------------


def render_pins(
    version: str,
    released: str,
    binaries: Mapping[str, tuple[str, str, str]],
    default: str,
    profiles: Iterable[str],
) -> str:
    lines = [
        '"""What tlsmask bundles. Generated by scripts/bump.py from a tls-client release; do not edit."""',
        "",
        "from __future__ import annotations",
        "",
        f'LIBRARY_VERSION = "{version}"',
        f'LIBRARY_RELEASED = "{released}"',
        "",
        "# target -> (upstream release asset, its SHA-256, wheel platform tag)",
        "BINARIES: dict[str, tuple[str, str, str]] = {",
    ]
    for target in upstream.TARGET_ORDER:
        asset, digest, tag = binaries[target]
        lines += [
            f'    "{target}": (',
            f'        "{asset}",',
            f'        "{digest}",',
            f'        "{tag}",',
            "    ),",
        ]
    lines += [
        "}",
        "",
        f'DEFAULT_PROFILE = "{default}"',
        "",
        "PROFILES: frozenset[str] = frozenset(",
        "    {",
    ]
    lines += [f'        "{name}",' for name in sorted(profiles)]
    lines += ["    }", ")", ""]
    return "\n".join(lines)


def render_profiles_module(version: str, profiles: Iterable[str]) -> str:
    lines = [
        f'"""Every profile name bogdanfinn/tls-client {version} ships, as a type for editors.',
        "",
        "Generated by scripts/bump.py; do not edit.",
        '"""',
        "",
        "from __future__ import annotations",
        "",
        "from typing import Literal",
        "",
        "ClientIdentifier = Literal[",
    ]
    lines += [f'    "{name}",' for name in sorted(profiles)]
    lines += [
        "]",
        "",
        "# The old tls-client package's name for the same type.",
        "ClientIdentifiers = ClientIdentifier",
        "",
    ]
    return "\n".join(lines)


def render_version(version: str) -> str:
    return (
        '"""tlsmask\'s version: the bundled tls-client version, plus a fourth number for\n'
        'wrapper-only releases (1.16.0.1, 1.16.0.2, ...)."""\n'
        "\n"
        f'__version__ = "{version}"\n'
    )


# --- README blocks -------------------------------------------------------------


def render_badge(version: str) -> str:
    # HTML, not Markdown: GitHub leaves Markdown on a line starting with "<!--" as raw text
    return (
        f'<a href="https://github.com/bogdanfinn/tls-client/releases/tag/v{version}">'
        f'<img src="https://img.shields.io/badge/bundles_tls--client-v{version}-0a7cff" '
        f'alt="bundles tls-client v{version}"></a>'
    )


def render_stats(version: str, released: str, profiles: Iterable[str]) -> str:
    profiles = list(profiles)
    rows = [
        ("bogdanfinn/tls-client inside", OLD_WRAPPER["library"], f"v{version}"),
        ("Browser & app profiles", OLD_WRAPPER["profiles"], str(len(profiles))),
        ("Newest Chrome", OLD_WRAPPER["chrome"], newest(profiles, CHROME)),
        ("Newest Firefox", OLD_WRAPPER["firefox"], newest(profiles, FIREFOX)),
        ("Newest iOS Safari", OLD_WRAPPER["ios"], newest(profiles, SAFARI_IOS)),
        ("Brave", "none", newest(profiles, BRAVE)),
        ("Last updated", OLD_WRAPPER["updated"], month_year(released)),
        ("Native library checked against a pinned SHA-256", "no", "yes, at build and at load"),
        ("Keeps itself current", "no", "yes, a weekly bot"),
    ]
    lines = ["", "| | `tls-client` (the old wrapper) | **tlsmask** |", "|---|:---:|:---:|"]
    lines += [f"| {label} | {old} | **{new}** |" for label, old, new in rows]
    return "\n".join(lines) + "\n"


def render_profile_table(version: str, profiles: Iterable[str]) -> str:
    profiles = list(profiles)
    lines = [
        "",
        "<details>",
        f"<summary><b>All {len(profiles)} profiles in tls-client v{version}</b></summary>",
        "",
        "| Family | Profiles |",
        "|---|---|",
    ]
    for label in [name for name, _ in FAMILIES] + [OTHERS]:
        names = sorted((p for p in profiles if family(p) == label), key=natural)
        if names:
            lines.append(f"| {label} | {' '.join(f'`{name}`' for name in names)} |")
    lines += ["", "</details>", ""]
    return "\n".join(lines)


def replace_block(text: str, name: str, content: str) -> str:
    pattern = re.compile(rf"(<!-- {name}:start -->)(.*?)(<!-- {name}:end -->)", re.S)
    if not pattern.search(text):
        raise ValueError(f"no <!-- {name}:start --> ... <!-- {name}:end --> block")
    return pattern.sub(lambda m: m.group(1) + content + m.group(3), text, count=1)


def refresh_readme(text: str, version: str, released: str, profiles: Iterable[str]) -> str:
    profiles = list(profiles)
    text = replace_block(text, "badge", render_badge(version))
    text = replace_block(text, "stats", render_stats(version, released, profiles))
    return replace_block(text, "profiles", render_profile_table(version, profiles))


# --- changelog -----------------------------------------------------------------


def changelog_entry(
    version: str, date: str, url: str, added: Sequence[str], removed: Sequence[str]
) -> str:
    lines = [f"## {version} - {date}", "", f"Bundles bogdanfinn/tls-client [v{version}]({url})."]
    if added or removed:
        lines.append("")
    if added:
        lines.append(f"- New profiles: {_codes(added)}")
    if removed:
        lines.append(f"- Removed profiles: {_codes(removed)}")
    return "\n".join(lines) + "\n"


def add_changelog_entry(changelog: str, entry: str) -> str:
    head, sep, rest = changelog.partition("\n## ")
    if not sep:
        return changelog.rstrip("\n") + "\n\n" + entry
    return head.rstrip("\n") + "\n\n" + entry + "\n## " + rest


def changelog_section(changelog: str, version: str) -> str:
    match = re.search(
        rf"^## {re.escape(version)}(?:\s[^\n]*)?\n(.*?)(?=^## |\Z)", changelog, re.M | re.S
    )
    if not match:
        raise ValueError(f"CHANGELOG.md has no section for {version}")
    return match.group(1).strip()


# --- the update bot's pull request ---------------------------------------------


def render_report(
    *,
    version: str,
    old_version: str,
    url: str,
    released: str,
    age_days: int,
    reasons: Sequence[str],
    added: Sequence[str],
    removed: Sequence[str],
    old_default: str,
    default: str,
    old_count: int,
    api: Mapping[str, Sequence[str]],
    binaries: Mapping[str, tuple[str, str, str]],
    notes: Sequence[tuple[str, str]],
) -> str:
    if reasons:
        verdict = "**Ships by itself:** no. It waits for a human merge because:\n" + "\n".join(
            f"- {reason}" for reason in reasons
        )
    else:
        verdict = "**Ships by itself:** yes, every check passed (tests run next)."
    lines = [
        f"## bogdanfinn/tls-client v{old_version} -> [v{version}]({url})",
        "",
        verdict,
        "",
        "| | |",
        "|---|---|",
        f"| Released | {released} ({age_days} days ago) |",
        f"| Profiles | {old_count} -> {old_count + len(added) - len(removed)} |",
        f"| Default profile | `{old_default}` -> `{default}` |",
        "",
        "### Profiles",
        "",
        f"- Added: {_codes(added) or 'none'}",
        f"- Removed: {_codes(removed) or 'none'}",
        "",
        "### JSON API (cffi_src/types.go, cffi_dist/main.go)",
        "",
        f"- Added fields: {_codes(api['added']) or 'none'}",
        f"- Removed fields: {_codes(api['removed']) or 'none'}",
        f"- Retyped fields: {_codes(api['retyped']) or 'none'}",
        f"- C functions added: {_codes(api['exports_added']) or 'none'}",
        f"- C functions removed: {_codes(api['exports_removed']) or 'none'}",
        "",
        "### Files (each SHA-256 matches the digest GitHub publishes)",
        "",
        "| Target | Asset | SHA-256 | Wheel tag |",
        "|---|---|---|---|",
    ]
    lines += [f"| {t} | `{a}` | `{d}` | `{tag}` |" for t, (a, d, tag) in binaries.items()]
    lines += ["", "### Upstream release notes", ""]
    for tag, body in notes:
        lines += [f"#### {tag}", "", body.strip() or "(no notes)", ""]
    return "\n".join(lines) + "\n"


# --- CLI -----------------------------------------------------------------------


def refresh(root: Path = upstream.ROOT) -> list[str]:
    """Re-render every generated file from the current pins; returns what changed."""
    pins = upstream.load_module(root / "tlsmask" / "_pins.py")
    version = upstream.load_module(root / "tlsmask" / "_version.py").__version__
    readme = (root / "README.md").read_text(encoding="utf-8")
    outputs = {
        "tlsmask/_pins.py": render_pins(
            pins.LIBRARY_VERSION,
            pins.LIBRARY_RELEASED,
            pins.BINARIES,
            pins.DEFAULT_PROFILE,
            pins.PROFILES,
        ),
        "tlsmask/profiles.py": render_profiles_module(pins.LIBRARY_VERSION, pins.PROFILES),
        "tlsmask/_version.py": render_version(version),
        "README.md": refresh_readme(
            readme, pins.LIBRARY_VERSION, pins.LIBRARY_RELEASED, pins.PROFILES
        ),
    }
    changed = []
    for relative, content in outputs.items():
        path = root / relative
        if path.read_text(encoding="utf-8") != content:
            path.write_bytes(content.encode("utf-8"))
            changed.append(relative)
    return changed


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    commands = parser.add_subparsers(dest="command", required=True)
    commands.add_parser("refresh")
    commands.add_parser("changelog-section").add_argument("version")
    args = parser.parse_args(argv)
    if args.command == "refresh":
        changed = refresh()
        print("\n".join(changed) if changed else "everything is current")
    else:
        text = (upstream.ROOT / "CHANGELOG.md").read_text(encoding="utf-8")
        print(changelog_section(text, args.version))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
